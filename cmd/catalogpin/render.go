// PE layout offsets, from the Microsoft PE format: the pointer to the PE
// header sits at 0x3c of the DOS header, the optional header 24 bytes after
// the PE signature, and the subsystem 68 bytes into a PE32+ optional header.
const (
	peOffsetPointer  = 0x3c
	peOptionalHeader = 24
	peSubsystem      = 68
	pe32PlusMagic    = 0x20b
	subsystemEFIApp  = 10

	// dosHeaderLen is the DOS header's length: it ends with the PE pointer.
	dosHeaderLen = peOffsetPointer + 4
	// maxPEOffset bounds where the PE header may start. A pointer past it is
	// no stub, so a crafted file cannot make readEFIHeader read far.
	maxPEOffset = 64 << 10
)

// readEFIHeader reads from r the bytes efiStub needs: the DOS header, then the
// bytes through the subsystem field of the PE header it points to. A PE header
// in a real EFI binary can sit well past the DOS header (the UEFI Shell's
// AArch64 build has it at 3672), so no fixed window serves. It reads no more
// than maxPEOffset and the PE fields, and no more than the file holds; the
// caller hashes the rest of r after the bytes returned.
func readEFIHeader(r io.Reader) ([]byte, error) {
	head, err := readUpTo(r, make([]byte, dosHeaderLen))
	if err != nil || len(head) < dosHeaderLen {
		return head, err
	}
	e := uint64(binary.LittleEndian.Uint32(head[peOffsetPointer:]))
	if e > maxPEOffset {
		return head, nil
	}
	end := e + peOptionalHeader + peSubsystem + 2
	more, err := readUpTo(r, make([]byte, end-dosHeaderLen))
	return append(head, more...), err
}

// readUpTo fills buf from r, or as far as r goes: a short read is not an error.
func readUpTo(r io.Reader, buf []byte) ([]byte, error) {
	n, err := io.ReadFull(r, buf)
	if errors.Is(err, io.EOF) || errors.Is(err, io.ErrUnexpectedEOF) {
		err = nil
	}
	return buf[:n], err
}

// efiStub reports whether header, the first bytes of a file, opens an
// executable that UEFI firmware can start: MZ, a PE header at the offset the
// DOS header names, the PE32+ magic, and the EFI-application subsystem.
func efiStub(header []byte) bool {
	if len(header) < peOffsetPointer+4 || header[0] != 'M' || header[1] != 'Z' {
		return false
	}
	e := uint64(binary.LittleEndian.Uint32(header[peOffsetPointer:]))
	if e+peOptionalHeader+peSubsystem+2 > uint64(len(header)) {
		return false
	}
	return string(header[e:e+4]) == "PE\x00\x00" &&
		binary.LittleEndian.Uint16(header[e+peOptionalHeader:]) == pe32PlusMagic &&
		binary.LittleEndian.Uint16(header[e+peOptionalHeader+peSubsystem:]) == subsystemEFIApp
}

// compareKeys orders keys by entry, then architecture.
func compareKeys(a, b catalog.Key) int {
	return cmp.Or(strings.Compare(a.Entry, b.Entry), strings.Compare(a.Arch, b.Arch))
}

// render returns the source of internal/catalog/catalog_pins.go for pins and
// absent: gofmt-formatted, with both maps in key order.
func render(pins map[catalog.Key]catalog.Pin, absent map[catalog.Key]string) ([]byte, error) {
	var b strings.Builder
	b.WriteString("// Code generated by cmd/catalogpin; DO NOT EDIT.\n\npackage catalog\n\n")
	b.WriteString("// pins holds the generated pin of every entry `task catalog:pin` has pinned.\n")
	b.WriteString("var pins = map[Key]Pin{")
	for _, k := range slices.SortedFunc(maps.Keys(pins), compareKeys) {
		fmt.Fprintf(&b, "\n%s: ", keyLiteral(k))
		writePin(&b, pins[k])
		b.WriteString(",")
	}
	if len(pins) > 0 {
		b.WriteString("\n")
	}
	b.WriteString("}\n\n")
	b.WriteString("// absent holds the reason each entry has no pin: the ledger of entries the\n")
	b.WriteString("// pin step could not or did not pin.\n")
	b.WriteString("var absent = map[Key]string{")
	for _, k := range slices.SortedFunc(maps.Keys(absent), compareKeys) {
		fmt.Fprintf(&b, "\n%s: %q,", keyLiteral(k), absent[k])
	}
	if len(absent) > 0 {
		b.WriteString("\n")
	}
	b.WriteString("}\n")
	return format.Source([]byte(b.String()))
}

func keyLiteral(k catalog.Key) string {
	return fmt.Sprintf("{Entry: %q, Arch: %q}", k.Entry, k.Arch)
}

// writePin writes p as an elided composite literal. Zero Signer and EFIStub
// fields, and an empty Objects list, are left out.
func writePin(b *strings.Builder, p catalog.Pin) {
	fmt.Fprintf(b, "{\nID: %q,\n", p.ID)
	if len(p.Objects) > 0 {
		b.WriteString("Objects: []ObjectPin{\n")
		for _, o := range p.Objects {
			fmt.Fprintf(b, "{\nURL: %q,\nSize: %d,\nSHA256: %q,\n", o.URL, o.Size, o.SHA256)
			if o.Signer != "" {
				fmt.Fprintf(b, "Signer: %q,\n", o.Signer)
			}
			b.WriteString("Files: []FilePin{\n")
			for _, f := range o.Files {
				fmt.Fprintf(b, "{Path: %q, Size: %d, SHA256: %q", f.Path, f.Size, f.SHA256)
				if f.EFIStub {
					b.WriteString(", EFIStub: true")
				}
				b.WriteString("},\n")
			}
			b.WriteString("},\n},\n")
		}
		b.WriteString("},\n")
	}
	b.WriteString("}")
}
