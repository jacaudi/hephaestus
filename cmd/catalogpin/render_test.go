func renderFixture() (map[catalog.Key]catalog.Pin, map[catalog.Key]string) {
	pins := map[catalog.Key]catalog.Pin{
		{Entry: "zeta", Arch: "arm64"}: {ID: "zzzzzzzzzzzz"},
		{Entry: "alpha", Arch: "amd64"}: {
			ID: "aaaaaaaaaaaa",
			Objects: []catalog.ObjectPin{{
				URL: "https://upstream.example.test/tool.zip", Size: 3, SHA256: hashABC, Signer: testFPR,
				Files: []catalog.FilePin{
					{Path: "bin/tool.efi", Size: 1, SHA256: hashFile, EFIStub: true},
					{Path: "readme.txt", Size: 2, SHA256: hashFile},
				},
			}},
		},
	}
	absent := map[catalog.Key]string{
		{Entry: "gamma", Arch: "amd64"}: "network: connection refused",
		{Entry: "beta", Arch: "arm64"}:  `signature: has "quotes"`,
	}
	return pins, absent
}

func TestRender_FormattedAndCompiles(t *testing.T) {
	pins, absent := renderFixture()
	src, err := render(pins, absent)
	if err != nil {
		t.Fatalf("render: %v", err)
	}
	formatted, err := format.Source(src)
	if err != nil {
		t.Fatalf("format.Source: %v", err)
	}
	if !bytes.Equal(formatted, src) {
		t.Errorf("render is not gofmt-clean:\n%s", src)
	}
	if !bytes.HasPrefix(src, []byte("// Code generated by cmd/catalogpin; DO NOT EDIT.\n")) {
		t.Errorf("render lacks the generated-code header:\n%s", src)
	}
	file, err := parser.ParseFile(token.NewFileSet(), "catalog_pins.go", src, parser.AllErrors)
	if err != nil {
		t.Fatalf("parse: %v", err)
	}
	if file.Name.Name != "catalog" {
		t.Errorf("package %q, want catalog", file.Name.Name)
	}
}

func TestRender_KeyOrderAndContent(t *testing.T) {
	pins, absent := renderFixture()
	src, err := render(pins, absent)
	if err != nil {
		t.Fatalf("render: %v", err)
	}
	got := string(src)
	for _, want := range []string{
		`Signer: "` + testFPR + `"`,
		`EFIStub: true`,
		`"signature: has \"quotes\""`,
		`Path: "readme.txt", Size: 2, SHA256: "` + hashFile + `"}`,
	} {
		if !strings.Contains(got, want) {
			t.Errorf("render lacks %s:\n%s", want, got)
		}
	}
	if strings.Count(got, "EFIStub") != 1 {
		t.Errorf("EFIStub is written for a file without a stub:\n%s", got)
	}
	if strings.Contains(got, `Signer: ""`) {
		t.Errorf("an empty Signer is written:\n%s", got)
	}
	order := func(a, b string) bool { return strings.Index(got, a) < strings.Index(got, b) }
	if !order(`Entry: "alpha"`, `Entry: "zeta"`) || !order(`Entry: "beta"`, `Entry: "gamma"`) {
		t.Errorf("keys are not in entry order:\n%s", got)
	}
}

// TestRender_MatchesCompiledInFile holds catalog_pins.go to render's own
// output: a hand edit, or a render that drifts from what the file was
// generated with, shows here.
func TestRender_MatchesCompiledInFile(t *testing.T) {
	want, err := os.ReadFile(filepath.Join("..", "..", "internal", "catalog", "catalog_pins.go"))
	if err != nil {
		t.Fatal(err)
	}
	got, err := render(catalog.Pins(), catalog.Absent())
	if err != nil {
		t.Fatalf("render: %v", err)
	}
	if !bytes.Equal(got, want) {
		t.Errorf("catalog_pins.go is not what render produces from its own pins:\n--- render ---\n%s\n--- file ---\n%s", got, want)
	}
}

// peImage returns an image of an executable whose PE header starts at e, as a
// real EFI binary may place it: MZ, e at 0x3c, then "PE\0\0", the PE32+ magic
// and the subsystem at e, and 512 bytes of body after.
func peImage(e uint32, subsystem uint16) []byte {
	b := make([]byte, int(e)+512)
	copy(b, "MZ")
	binary.LittleEndian.PutUint32(b[peOffsetPointer:], e)
	copy(b[e:], "PE\x00\x00")
	binary.LittleEndian.PutUint16(b[e+peOptionalHeader:], pe32PlusMagic)
	binary.LittleEndian.PutUint16(b[e+peOptionalHeader+peSubsystem:], subsystem)
	return b
}

// countReader counts the bytes read through it.
type countReader struct {
	r io.Reader
	n int
}

func (c *countReader) Read(p []byte) (int, error) {
	n, err := c.r.Read(p)
	c.n += n
	return n, err
}

func TestReadEFIHeader(t *testing.T) {
	const maxRead = maxPEOffset + peOptionalHeader + peSubsystem + 2
	tests := []struct {
		name     string
		image    []byte
		wantStub bool
		maxBytes int // most bytes the read may take from the file
	}{
		{"PE header at 1137, as in memtest86+ x86_64", peImage(1137, 10), true, maxRead},
		{"PE header at 3672, as in the UEFI Shell AArch64", peImage(3672, 10), true, maxRead},
		{"PE header at the bound", peImage(maxPEOffset, 10), true, maxRead},
		{"PE header past the bound", peImage(maxPEOffset+1, 10), false, dosHeaderLen},
		{"PE offset overflowing", func() []byte {
			b := peImage(1137, 10)
			binary.LittleEndian.PutUint32(b[peOffsetPointer:], 0xffffffff)
			return b
		}(), false, dosHeaderLen},
		{"PE header at 1137, a console subsystem", peImage(1137, 3), false, maxRead},
		{"file cut inside the PE header", peImage(1137, 10)[:1137+30], false, maxRead},
		{"file shorter than the DOS header", []byte("MZ"), false, dosHeaderLen},
		{"empty file", nil, false, dosHeaderLen},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			src := &countReader{r: bytes.NewReader(tt.image)}

			head, err := readEFIHeader(src)

			if err != nil {
				t.Fatalf("readEFIHeader: %v", err)
			}
			if got := efiStub(head); got != tt.wantStub {
				t.Errorf("efiStub = %t, want %t", got, tt.wantStub)
			}
			if src.n > tt.maxBytes {
				t.Errorf("read %d bytes, want at most %d", src.n, tt.maxBytes)
			}
			rest, err := io.ReadAll(src)
			if err != nil {
				t.Fatalf("ReadAll: %v", err)
			}
			if whole := append(slices.Clone(head), rest...); !bytes.Equal(whole, tt.image) {
				t.Errorf("head and the rest are %d bytes that differ from the %d byte image", len(whole), len(tt.image))
			}
		})
	}
}

func TestReadEFIHeader_ReadError(t *testing.T) {
	boom := errors.New("boom")

	_, err := readEFIHeader(io.MultiReader(bytes.NewReader(peImage(1137, 10)[:100]), iotest.ErrReader(boom)))

	if !errors.Is(err, boom) {
		t.Errorf("readEFIHeader error = %v, want %v", err, boom)
	}
}
