// peHeader returns 512 bytes that open a PE32+ image with the given subsystem:
// MZ, the PE offset 0x80 at 0x3c, "PE\0\0" there, the PE32+ magic and the
// subsystem in the optional header.
func peHeader(subsystem uint16) []byte {
	b := make([]byte, 512)
	copy(b, "MZ")
	binary.LittleEndian.PutUint32(b[0x3c:], 0x80)
	copy(b[0x80:], "PE\x00\x00")
	binary.LittleEndian.PutUint16(b[0x80+24:], 0x20b)
	binary.LittleEndian.PutUint16(b[0x80+24+68:], subsystem)
	return b
}

func TestEFIStub(t *testing.T) {
	const peOff = 0x80
	tests := []struct {
		name   string
		header []byte
		want   bool
	}{
		{"an EFI application", peHeader(10), true},
		{"a console subsystem", peHeader(3), false},
		{"a boot service driver", peHeader(11), false},
		{"empty", nil, false},
		{"no MZ", append([]byte("XZ"), peHeader(10)[2:]...), false},
		{"MZ and nothing after", []byte("MZ"), false},
		{"PE signature wrong", func() []byte { b := peHeader(10); b[peOff] = 'X'; return b }(), false},
		{"PE32 magic, not PE32+", func() []byte { b := peHeader(10); binary.LittleEndian.PutUint16(b[peOff+24:], 0x10b); return b }(), false},
		{"PE offset past the header", func() []byte { b := peHeader(10); binary.LittleEndian.PutUint32(b[0x3c:], 600); return b }(), false},
		{"PE offset overflowing", func() []byte { b := peHeader(10); binary.LittleEndian.PutUint32(b[0x3c:], 0xffffffff); return b }(), false},
		{"header cut before the subsystem", peHeader(10)[:peOff+24+68], false},
		{"plain text", bytes.Repeat([]byte("plain "), 100), false},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := efiStub(tt.header); got != tt.want {
				t.Errorf("efiStub = %t, want %t", got, tt.want)
			}
		})
	}
}

const (
	hashABC  = "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad"
	hashFile = "2d711642b726b04401627ca9fbac32f5c8530fb1903cc4db02258717921a4881"
)

func renderFixture() (map[catalog.Key]catalog.Pin, map[catalog.Key]string) {
	pins := map[catalog.Key]catalog.Pin{
		{Entry: "zeta", Arch: "arm64"}: {ID: "zzzzzzzzzzzz"},
		{Entry: "alpha", Arch: "amd64"}: {
			ID: "aaaaaaaaaaaa",
			Objects: []catalog.ObjectPin{{
				URL: "https://upstream.example.test/tool.zip", Size: 3, SHA256: hashABC, Signer: testFPR,
				Files: []catalog.FilePin{
					{Path: "bin/tool.efi", Size: 1, SHA256: hashFile, EFIStub: true},
					{Path: "readme.txt", Size: 2, SHA256: hashFile},
				},
			}},
		},
	}
	absent := map[catalog.Key]string{
		{Entry: "gamma", Arch: "amd64"}: "network: connection refused",
		{Entry: "beta", Arch: "arm64"}:  `signature: has "quotes"`,
	}
	return pins, absent
}

func TestRender_FormattedAndCompiles(t *testing.T) {
	pins, absent := renderFixture()
	src, err := render(pins, absent)
	if err != nil {
		t.Fatalf("render: %v", err)
	}
	formatted, err := format.Source(src)
	if err != nil {
		t.Fatalf("format.Source: %v", err)
	}
	if !bytes.Equal(formatted, src) {
		t.Errorf("render is not gofmt-clean:\n%s", src)
	}
	if !bytes.HasPrefix(src, []byte("// Code generated by cmd/catalogpin; DO NOT EDIT.\n")) {
		t.Errorf("render lacks the generated-code header:\n%s", src)
	}
	file, err := parser.ParseFile(token.NewFileSet(), "catalog_pins.go", src, parser.AllErrors)
	if err != nil {
		t.Fatalf("parse: %v", err)
	}
	if file.Name.Name != "catalog" {
		t.Errorf("package %q, want catalog", file.Name.Name)
	}
}

func TestRender_KeyOrderAndContent(t *testing.T) {
	pins, absent := renderFixture()
	src, err := render(pins, absent)
	if err != nil {
		t.Fatalf("render: %v", err)
	}
	got := string(src)
	for _, want := range []string{
		`Signer: "` + testFPR + `"`,
		`EFIStub: true`,
		`"signature: has \"quotes\""`,
		`Path: "readme.txt", Size: 2, SHA256: "` + hashFile + `"}`,
	} {
		if !strings.Contains(got, want) {
			t.Errorf("render lacks %s:\n%s", want, got)
		}
	}
	if strings.Count(got, "EFIStub") != 1 {
		t.Errorf("EFIStub is written for a file without a stub:\n%s", got)
	}
	if strings.Contains(got, `Signer: ""`) {
		t.Errorf("an empty Signer is written:\n%s", got)
	}
	order := func(a, b string) bool { return strings.Index(got, a) < strings.Index(got, b) }
	if !order(`Entry: "alpha"`, `Entry: "zeta"`) || !order(`Entry: "beta"`, `Entry: "gamma"`) {
		t.Errorf("keys are not in entry order:\n%s", got)
	}
}

// TestRender_MatchesCompiledInFile holds catalog_pins.go to render's own
// output: a hand edit, or a render that drifts from what the file was
// generated with, shows here.
func TestRender_MatchesCompiledInFile(t *testing.T) {
	want, err := os.ReadFile(filepath.Join("..", "..", "internal", "catalog", "catalog_pins.go"))
	if err != nil {
		t.Fatal(err)
	}
	got, err := render(catalog.Pins(), catalog.Absent())
	if err != nil {
		t.Fatalf("render: %v", err)
	}
	if !bytes.Equal(got, want) {
		t.Errorf("catalog_pins.go is not what render produces from its own pins:\n--- render ---\n%s\n--- file ---\n%s", got, want)
	}
}
